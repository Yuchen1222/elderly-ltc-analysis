from src.data_processing import load_all, year_stats
from src.model import fit, odds_ratios

st.set_page_config(page_title="研究結論", layout="wide")
apply_styles()
st.title("研究結論與政策建議")
st.caption("本頁彙整全部分析結果，對應競賽報告之推論與討論章節")

@st.cache_data
def get_key_stats():
    data  = load_all()
    stats = year_stats(data)
    model = fit(data)
    or_df = odds_ratios(model)
    sev_or = or_df[or_df['原始欄位'] == '嚴重度']['勝算比'].values[0]
    age_or = or_df[or_df['原始欄位'] == '年齡']['勝算比'].values[0]
    inc_or = or_df[or_df['原始欄位'] == '低收入身分類別']['勝算比'].values[0]
    peak   = stats.loc[stats['使用率'].idxmax()]
    return {
        'stats':   stats,
        'sev_or':  sev_or,
        'age_or':  age_or,
        'inc_or':  inc_or,
        'peak_year': int(peak['年份']),
        'peak_rate': peak['使用率'],
        'rate_108':  stats[stats['年份']==108]['使用率'].values[0],
        'rate_112':  stats[stats['年份']==112]['使用率'].values[0],
    }

ks = get_key_stats()

# ── 執行摘要 ──────────────────────────────────────────────────────────────────
st.markdown("""
<div style="background:#E3F2FD;border-left:5px solid #1976D2;padding:1.2rem 1.5rem;border-radius:6px;margin-bottom:1.5rem">
<b>執行摘要</b><br>
本研究以民國 108 至 112 年銀髮安居模擬資料，分析台灣高齡族群長照服務使用的時間趨勢與影響因素。
結果顯示，長照使用率呈階段性變化而非單調上升，於 <b>民國 {peak_year} 年達到高峰（{peak_rate:.1f}%）</b>後逐年下降，
揭示長照「<b>需求－使用落差</b>」的存在。
身心障礙嚴重度（OR={sev_or:.2f}）與年齡（OR={age_or:.2f}）是最顯著的正向預測因子；
家庭支持與醫療可近性則呈替代效應，低收入族群存在明顯的使用障礙。
</div>
""".format(**ks), unsafe_allow_html=True)

st.markdown("---")

# ── 核心發現 ──────────────────────────────────────────────────────────────────
st.header("核心研究發現")

with st.expander("**發現一：長照使用率呈階段性變化，非線性成長**", expanded=True):
    col_l, col_r = st.columns([2, 1])
    with col_l:
        st.markdown(f"""
**觀察結果：**
長照使用率從民國 108 年的 **{ks['rate_108']:.1f}%** 上升至 {ks['peak_year']} 年的 **{ks['peak_rate']:.1f}%**，
隨後於 111、112 年逐步下降至 **{ks['rate_112']:.1f}%**。

**可能解釋：**
- **疫情效應（COVID-19）：** 110 年前後台灣進入防疫高峰，部分長者可能因疫情期間需求升高而增加服務申請，111 年後回落
- **服務供給瓶頸：** 長照服務提供者數量未能同步擴張，造成部分需求無法滿足（林彩雲、蘇琦雯，2022）
- **政策調整期：** 長照 2.0 政策施行後的評估與調整階段，資格認定與服務流程仍在磨合

**研究意涵：**
使用率的下降**不代表需求下降**，更可能反映服務可近性或申請便利性的不足。
這與 Lin 等（2021）根據健保資料的分析結論一致。
        """)
    with col_r:
        st.metric("108年使用率", f"{ks['rate_108']:.1f}%")
        st.metric(f"{ks['peak_year']}年使用率（高峰）", f"{ks['peak_rate']:.1f}%",
                  f"+{ks['peak_rate']-ks['rate_108']:.1f}%")
        st.metric("112年使用率", f"{ks['rate_112']:.1f}%",
                  f"{ks['rate_112']-ks['peak_rate']:.1f}%")

with st.expander("**發現二：身心障礙程度與年齡為最強正向預測因子**", expanded=True):
    col_l, col_r = st.columns([2, 1])
    with col_l:
        st.markdown(f"""
**觀察結果：**
邏輯斯迴歸結果顯示，**身心障礙嚴重度**（OR={ks['sev_or']:.2f}）與**年齡**（OR={ks['age_or']:.2f}）
是影響長照使用機率最顯著的正向因子（p < 0.001）。

**解讀：**
- 嚴重度每增加一個單位，使用長照的勝算約提升 **{(ks['sev_or']-1)*100:.0f}%**
- 每增加一歲，使用長照的勝算約提升 **{(ks['age_or']-1)*100:.0f}%**
- 此結果與羅玉岱（2011）對居家失能患者的分析高度一致

**政策意涵：**
障礙程度與年齡是不可改變的風險因子，但其影響可透過**及早識別、主動評估**來降低。
建立以障礙程度與年齡為篩選指標的「主動外展機制」，可有效提升高風險族群的服務可近性。
        """)
    with col_r:
        st.metric("身障嚴重度 OR", f"{ks['sev_or']:.3f}", "最強正向因子")
        st.metric("年齡 OR", f"{ks['age_or']:.3f}")
        st.info("OR > 1 代表該因素越高，使用長照機率越大")

with st.expander("**發現三：家庭支持對正式長照具替代效果**", expanded=True):
    st.markdown("""
**觀察結果：**
族群比較分析顯示，**與子女同住**或**子女同縣市**的長者，其長照服務使用率相對低於無家庭支持者。
「家庭型態」在邏輯斯迴歸中呈現負向係數，顯示家庭越完整，對正式照護的依賴越低。

**解讀：**
非正式照護（家人提供的日常協助）能部分取代正式長照服務，這並非政策失敗，而是台灣家庭文化的反映。
然而，過度依賴家庭非正式照護可能導致：
1. **照顧者負荷過重**：主要照顧者（多為女性）長期承受身心壓力
2. **需求低估風險**：因家人代為照顧而未進入正式評估系統，實際需求被隱藏

**政策意涵：**
政策設計應同時考量**家庭照顧者的支持**（如喘息服務），而非僅關注被照顧者的需求（劉正、齊力，2018）。
    """)

with st.expander("**發現四：低收入族群面臨使用障礙，補助政策效益有限**", expanded=True):
    st.markdown(f"""
**觀察結果：**
低收入身分類別的勝算比（OR={ks['inc_or']:.3f}）小於 1，代表即使有政府補助，
低收入長者的長照使用率仍**低於一般戶**。

**解讀：**
補助政策降低了「金錢成本」，但未解決：
- **資訊不對稱**：低收入長者不知道有哪些服務可以申請
- **申請複雜度**：文件準備與行政流程對識字率低或無人協助者構成障礙
- **文化因素**：部分族群存在對政府服務的不信任或羞恥感

此發現與廖彩雲、蘇琦雯（2022）關於「服務意願與實際使用落差」的結論一致。

**政策意涵：**
需搭配**主動外展**與**個案管理員制度**，協助弱勢族群突破資訊與申請障礙。
    """)

st.markdown("---")

# ── 政策建議 ──────────────────────────────────────────────────────────────────
st.header("政策建議")
st.markdown("以下四項建議均有本研究實證支持，對應不同層面的服務輸送障礙。")

p1, p2 = st.columns(2)
p3, p4 = st.columns(2)

with p1:
    st.markdown("""
**建議一：強化居家與社區照護網絡**

民國 111–112 年使用率下降顯示，服務供給端尚未能滿足持續成長的需求。
應擴大居家服務覆蓋範圍，特別針對：
- 無電梯公寓住戶（行動限制）
- 醫療資源不足的偏遠地區

**對應發現：** 距離醫院距離 OR < 1，顯示可近性直接影響使用率

**參考：** 丁施丹等（2023）
    """)

with p2:
    st.markdown(f"""
**建議二：建立高風險族群主動篩查機制**

以身心障礙程度（OR={ks['sev_or']:.2f}）與年齡（OR={ks['age_or']:.2f}）為主要篩查指標，
建立「長照需求預警系統」：
- 整合健保資料、身障證明資料
- 定期主動接觸未使用服務的高風險長者
- 提供入戶評估服務

**目標：** 縮短「需求產生」到「服務使用」的時間差
    """)

with p3:
    st.markdown(f"""
**建議三：提升弱勢族群服務可近性**

針對低收入族群（OR={ks['inc_or']:.3f}）的使用障礙，補助政策之外需要：
- **個案管理員制度**：指定專人協助申請流程
- **簡化申辦流程**：減少文件要求，提供多語言說明
- **社區據點連結**：透過里長、社區發展協會等在地組織傳遞資訊

**目標：** 將補助政策的實際觸達率從不足 50% 提升至 80% 以上
    """)

with p4:
    st.markdown("""
**建議四：重視家庭照顧者的支持需求**

家庭支持雖降低正式長照依賴，但會轉嫁成照顧者負荷。
應擴大：
- **喘息服務**：讓主要照顧者能有休息時間
- **照顧技能培訓**：提升家庭照顧品質
- **心理健康支持**：預防照顧者身心耗竭

**目標：** 建立「被照顧者＋照顧者」雙軌支持體系（劉正、齊力，2018）
    """)

st.markdown("---")

# ── 研究限制 ──────────────────────────────────────────────────────────────────
st.header("研究限制與未來方向")
col_l, col_r = st.columns(2)

with col_l:
    st.subheader("研究限制")
    st.markdown("""
1. **資料為模擬資料**：銀髮安居資料為模擬資料集，結論不能直接推論至真實人口，
   但分析框架可延伸至健保資料庫或長照資訊系統

2. **橫斷面設計**：各年度資料為獨立樣本而非追蹤同一群體，
   無法排除世代效應（cohort effect）對趨勢的影響

3. **遺漏變數**：未能納入認知功能、心理健康狀況、照顧者可用性等可能的混淆因子

4. **因果推論限制**：邏輯斯迴歸建立相關性，不代表因果關係；
   距離醫院越近長照使用率越高，反映的是「可近性」而非「醫院導致需求」
    """)

with col_r:
    st.subheader("未來研究方向")
    st.markdown("""
1. **使用真實資料**：申請衛福部長照資訊系統或 NHRI 資料庫，
   以真實個案資料驗證本研究發現

2. **縣市層級分析**：將分析模式擴展至縣市層級，
   比較都市與鄉村在長照資源配置上的差異

3. **時間序列預測**：建立 ARIMA 或 LSTM 模型預測未來長照需求趨勢，
   作為政府資源配置的參考依據

4. **長照需求預警系統**：結合 AI 預測與即時健康資料，
   提前識別高風險族群並推送服務資訊
    """)

st.markdown("---")

